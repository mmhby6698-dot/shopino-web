const root = document.documentElement;
const header = document.querySelector(".site-header");
const langToggle = document.querySelector("#langToggle");
const navToggle = document.querySelector("#navToggle");
const siteNav = document.querySelector("#siteNav");
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

function setMeta(selector, attr, value) {
  const el = document.querySelector(selector);
  if (el && typeof value === "string") el.setAttribute(attr, value);
}

function setLanguage(lang, { persist = true } = {}) {
  const dict = translations[lang];
  if (!dict) return;

  root.lang = lang;
  root.dir = lang === "fa" ? "rtl" : "ltr";
  root.dataset.lang = lang;
  document.title = dict.metaTitle;

  setMeta('meta[name="description"]', "content", dict.metaDescription);
  setMeta('meta[property="og:title"]', "content", dict.ogTitle);
  setMeta('meta[property="og:description"]', "content", dict.ogDescription);
  setMeta('meta[property="og:locale"]', "content", dict.ogLocale);
  setMeta('meta[name="twitter:title"]', "content", dict.ogTitle);
  setMeta('meta[name="twitter:description"]', "content", dict.ogDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dict[element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = dict[element.dataset.i18nHtml];
    if (typeof value === "string") element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dict[element.dataset.i18nAria];
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  if (persist) {
    try { localStorage.setItem("shopino-lang", lang); } catch {}
    const url = new URL(location.href);
    url.searchParams.set("lang", lang);
    history.replaceState({}, "", url);
  }
}

function getInitialLang() {
  const params = new URLSearchParams(location.search);
  const fromUrl = params.get("lang");
  if (fromUrl === "en" || fromUrl === "fa") return fromUrl;
  try {
    const stored = localStorage.getItem("shopino-lang");
    if (stored === "en" || stored === "fa") return stored;
  } catch {}
  return "fa";
}

let currentLanguage = getInitialLang();
if (currentLanguage !== "fa") setLanguage(currentLanguage, { persist: false });

if (langToggle) {
  langToggle.addEventListener("click", () => {
    currentLanguage = currentLanguage === "fa" ? "en" : "fa";
    setLanguage(currentLanguage);
  });
}

function closeNav() {
  if (!navToggle || !siteNav) return;
  navToggle.setAttribute("aria-expanded", "false");
  siteNav.classList.remove("is-open");
  if (header) header.classList.remove("is-nav-open");
}

if (navToggle && siteNav) {
  navToggle.addEventListener("click", () => {
    const open = navToggle.getAttribute("aria-expanded") === "true";
    navToggle.setAttribute("aria-expanded", String(!open));
    siteNav.classList.toggle("is-open", !open);
    if (header) header.classList.toggle("is-nav-open", !open);
  });
  siteNav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeNav);
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeNav();
  });
}

const contactForm = document.querySelector("#contactForm");
const formResult = document.querySelector("#formResult");
const formPreview = document.querySelector("#formPreview");
const copyButton = document.querySelector("#copyMessage");

function buildPreparedMessage() {
  const dict = translations[currentLanguage] || translations.fa;
  const name = (document.querySelector("#contactName")?.value || "").trim();
  const needSelect = document.querySelector("#contactNeed");
  const needText = needSelect?.selectedOptions?.[0]?.textContent?.trim() || "";
  const note = (document.querySelector("#contactMsg")?.value || "").trim();
  const lead = (dict.formMessageLead || "").replace("{name}", name).replace("{need}", needText);
  return note ? `${lead}\n${note}` : lead;
}

if (contactForm && formResult && formPreview) {
  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();
    formPreview.textContent = buildPreparedMessage();
    formResult.hidden = false;
    formResult.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "nearest" });
  });
}

if (copyButton && formPreview) {
  copyButton.addEventListener("click", async () => {
    const text = formPreview.textContent;
    if (!text) return;
    const dict = translations[currentLanguage] || translations.fa;
    try {
      await navigator.clipboard.writeText(text);
      copyButton.textContent = dict.formCopied;
    } catch {
      const range = document.createRange();
      range.selectNodeContents(formPreview);
      const sel = window.getSelection();
      sel.removeAllRanges();
      sel.addRange(range);
    }
  });
}

let headerFrame = 0;
function updateHeader() {
  headerFrame = 0;
  if (!header) return;
  const scrolled = window.scrollY > 10;
  if (header.classList.contains("is-scrolled") !== scrolled) {
    header.classList.toggle("is-scrolled", scrolled);
  }
}
function queueHeader() {
  if (!headerFrame) headerFrame = requestAnimationFrame(updateHeader);
}
window.addEventListener("scroll", queueHeader, { passive: true });

const revealItems = document.querySelectorAll(".reveal");
revealItems.forEach((item) => {
  if (item.dataset.revealDelay) {
    item.style.setProperty("--reveal-delay", `${Number(item.dataset.revealDelay) || 0}ms`);
  }
});

function setupReveal() {
  if ("IntersectionObserver" in window && !reduceMotion) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.16, rootMargin: "0px 0px -8% 0px" });
    revealItems.forEach((item) => observer.observe(item));
  } else {
    revealItems.forEach((item) => item.classList.add("is-visible"));
  }
}

document.querySelectorAll(".logo-shell").forEach((shell) => {
  const logoImage = shell.querySelector("img");
  const logoFallback = shell.querySelector(".logo-fallback");
  if (!logoImage || !logoFallback) return;
  const showFallback = () => {
    shell.classList.add("is-fallback");
    logoImage.hidden = true;
  };
  logoImage.addEventListener("error", showFallback);
});

const heroVisual = document.querySelector(".hero-visual");
const deviceScene = document.querySelector("#deviceScene");
const hero = document.querySelector(".hero");
let pointerFrame = 0;
let scrollFrame = 0;
let targetX = 0;
let targetY = 0;
let currentX = 0;
let currentY = 0;
let visualRect = null;
let lastScrollRx = null;
let lastSceneShift = null;

function setSceneVars() {
  if (!deviceScene) return;
  currentX += (targetX - currentX) * 0.12;
  currentY += (targetY - currentY) * 0.12;
  deviceScene.style.setProperty("--rx", currentX.toFixed(3));
  deviceScene.style.setProperty("--ry", currentY.toFixed(3));
  if (Math.abs(targetX - currentX) > 0.002 || Math.abs(targetY - currentY) > 0.002) {
    pointerFrame = requestAnimationFrame(setSceneVars);
  } else {
    pointerFrame = 0;
  }
}

function queuePointerFrame() {
  if (!pointerFrame) pointerFrame = requestAnimationFrame(setSceneVars);
}

function measureVisualRect() {
  if (heroVisual) visualRect = heroVisual.getBoundingClientRect();
}

function updateScrollScene() {
  scrollFrame = 0;
  if (!deviceScene || !hero || reduceMotion) return;
  const rect = hero.getBoundingClientRect();
  measureVisualRect();
  const viewport = window.innerHeight || document.documentElement.clientHeight;
  const progress = Math.min(1, Math.max(0, (viewport - rect.top) / (viewport + rect.height * 0.65)));
  const nextRx = `${(-7 * progress).toFixed(2)}deg`;
  const nextShift = `${(34 * progress).toFixed(2)}`;
  if (nextRx !== lastScrollRx) {
    lastScrollRx = nextRx;
    deviceScene.style.setProperty("--scroll-rx", nextRx);
  }
  if (nextShift !== lastSceneShift) {
    lastSceneShift = nextShift;
    deviceScene.style.setProperty("--scene-shift", nextShift);
  }
}
function queueScrollScene() {
  if (!scrollFrame) scrollFrame = requestAnimationFrame(updateScrollScene);
}

function startScene() {
  setupReveal();
  queueHeader();
  window.addEventListener("scroll", queueScrollScene, { passive: true });
  window.addEventListener("resize", queueScrollScene, { passive: true });
  queueScrollScene();

  if (heroVisual && deviceScene && !reduceMotion) {
    const finePointer = window.matchMedia("(pointer: fine)").matches;
    if (finePointer) {
      heroVisual.addEventListener("pointermove", (event) => {
        const rect = visualRect;
        if (!rect || !rect.width || !rect.height) return;
        const x = ((event.clientX - rect.left) / rect.width - 0.5) * 2;
        const y = ((event.clientY - rect.top) / rect.height - 0.5) * 2;
        targetY = x * 7;
        targetX = y * -6;
        queuePointerFrame();
      });
      heroVisual.addEventListener("pointerleave", () => {
        targetX = 0;
        targetY = 0;
        queuePointerFrame();
      });
    }

    window.addEventListener("deviceorientation", (event) => {
      if (typeof event.gamma !== "number" || typeof event.beta !== "number") return;
      targetY = Math.max(-7, Math.min(7, event.gamma / 9));
      targetX = Math.max(-6, Math.min(6, (event.beta - 42) / -10));
      queuePointerFrame();
    }, { passive: true });
  }
}

requestAnimationFrame(startScene);
